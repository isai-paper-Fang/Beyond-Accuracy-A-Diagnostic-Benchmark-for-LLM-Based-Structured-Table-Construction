PASS, FAIL = [], []


def ck(name, got, want):
    (PASS if got == want else FAIL).append((name, got, want))


def wrap(payload, prose="ผมพิจารณาข้อมูลตามลำดับดังนี้ ..."):
    """ห่อ payload ให้เหมือนคำตอบจริง: ข้อความอิสระ + บล็อก json ปิดท้าย"""
    return prose + "\n\n```json\n" + json.dumps(payload, ensure_ascii=False, indent=1) + "\n```"


